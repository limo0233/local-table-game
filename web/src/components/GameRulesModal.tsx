interface Props { game: GameType; onClose: () => void }

export function GameRulesModal({ game, onClose }: Props) {
  const rules = RULES[game]
  if (!rules) return null
  return <div className="modal-backdrop" role="presentation" onClick={onClose}>
    <section className="game-modal rules-modal" role="dialog" aria-modal="true" aria-label={rules.title} onClick={event => event.stopPropagation()}>
      <header><div><CircleHelp size={20} /><h2>{rules.title}</h2></div><button type="button" aria-label="关闭游戏规则" onClick={onClose}><X size={20} /></button></header>
      <p className="rules-summary">{rules.summary}</p>
      <ul>{rules.items.map(item => <li key={item}>{item}</li>)}</ul>
    </section>
  </div>
}
